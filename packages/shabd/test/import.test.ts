describe('telling which tool made a site', () => {
  it('goes by the config file each tool has', async () => {
    expect(detectTools(await site(DOCUSAURUS))).toEqual(['docusaurus'])
    expect(detectTools(await site(STARLIGHT))).toEqual(['starlight'])
    expect(detectTools(await site(MKDOCS))).toEqual(['mkdocs'])
    // `.vitepress` is found in the folder given, and in `docs` inside it, where most projects keep it.
    const vitepress = await site(VITEPRESS)
    expect(detectTools(vitepress)).toEqual(['vitepress'])
    expect(detectTools(path.join(vitepress, 'docs'))).toEqual(['vitepress'])
    // Astro builds other things than documentation.
    expect(detectTools(await site({ 'astro.config.mjs': 'export default {}\n' }))).toEqual([])
  })

  it('asks for --from when it cannot tell, and goes by it when given', async () => {
    const unknown = await site({ 'docs/index.md': '# Hello\n' })
    await expect(importSite(unknown)).rejects.toThrow(/Could not tell which tool made the site/)
    await expect(importSite(unknown, { from: 'hugo' })).rejects.toThrow(/--from must be one of docusaurus, vitepress, starlight, mkdocs/)

    const two = await site({ ...MKDOCS, 'docusaurus.config.js': 'module.exports = {}\n' })
    await expect(importSite(two)).rejects.toThrow(/more than one tool \(docusaurus, mkdocs\)/)

    // No config at all: MkDocs' defaults are enough to find the pages.
    const result = await importSite(unknown, { from: 'mkdocs' })
    expect(result.tool).toBe('mkdocs')
    expect(errorsOf(result)).toEqual([])
    expect(await read(result.out, 'content/index.md')).toBe('# Hello\n')
  })
})

