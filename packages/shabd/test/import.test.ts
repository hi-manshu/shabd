const site = temporarySites()
const page = (...lines: string[]) => `${lines.join('\n')}\n`
/** What a conversion counted, such as `callout` twice. */
const converted = (conversion: Conversion) =>
  conversion.notes.flatMap((note) => (note.kind === 'converted' ? [note.what] : [])).sort()
/** What a conversion left for the author, as `line: message`. */
const manual = (conversion: Conversion) =>
  conversion.notes.flatMap((note) => (note.kind === 'manual' ? [`${note.line ?? ''}: ${note.message}`] : []))
// eslint-disable-next-line no-control-regex
const plain = (text: string) => text.replace(/\u001b\[[0-9;]*m/g, '')
const read = (dir: string, file: string) => readFile(path.join(dir, file), 'utf8')
/** Every file of a folder with its text, to show that an import left the source as it was. */
const snapshot = async (dir: string) => Object.fromEntries(await Promise.all((await listFiles(dir)).map(async (file) => [file, await read(dir, file)])))
/** What `shabd check` would call an error in the new site. */
const errorsOf = (result: ImportResult) => [...result.check.refused.map(plain), ...result.check.problems.filter((problem) => problem.level === 'error').map((problem) => problem.message)]

